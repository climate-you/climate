# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def generate(
    question_id: str,
    lat: float,
    lon: float,
    label: str,
    tile_store: Any,
    temperature_unit: str = "C",
) -> dict | None:
    """
    Build a templated answer for a location question, or None to fall back to
    the LLM. Returns {"answer", "locations", "charts", "follow_up_ids"}.
    """
    node = QUESTION_TREE.get(question_id)
    generator = _GENERATORS.get(question_id)
    if node is None or generator is None or not node.requires_location:
        return None

    # Short display name: "Paris, Île-de-France, France" → "Paris"
    short_label = label.split(",")[0].strip() or label

    try:
        result = generator(tile_store, lat, lon, short_label)
    except Exception:
        return None
    if result is None:
        return None
    answer, chart_spec = result

    from .canned import build_canned_charts

    locations = [{"label": short_label, "lat": lat, "lon": lon}]
    extra_region_ids = (chart_spec or {}).pop("extra_region_ids", None)
    charts = (
        build_canned_charts(locations, chart_spec, tile_store, temperature_unit)
        if chart_spec
        else []
    )
    if extra_region_ids:
        from . import tools as _tools
        from .orchestrator import _build_chart_payloads

        series_results = []
        for region_id in extra_region_ids:
            r = _tools.get_region_metric_series(
                region_id=region_id,
                metric_id=chart_spec["metric_id"],
                aggregation="mean",
                tile_store=tile_store,
                temperature_unit=temperature_unit,
            )
            if "error" not in r and "data" in r:
                series_results.append(r)
        if series_results and charts:
            # Merge region series into the local chart (same metric).
            for extra in _build_chart_payloads(series_results, tile_store):
                if extra["series"]:
                    charts[0]["series"].extend(extra["series"])

    return {
        "answer": answer,
        "locations": locations,
        "charts": charts,
        "follow_up_ids": node.follow_up_ids,
    }
