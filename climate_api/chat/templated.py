"""
Template-generated answers for location-specific example questions.

Suggested questions that require a location ("How has the temperature changed
in {location}?") are generated by us, so no LLM is needed to interpret them —
and their answers always follow the same shape. This module computes the
numbers directly from the tile store and fills a per-question template,
producing the same (answer, locations, charts, follow_up_ids) payload as a
canned answer. The LLM remains the fallback for anything this module cannot
answer (unknown question id, missing data at the location).

Temperature values are encoded as [[C|F]] tokens, resolved by
canned._apply_unit at stream time, exactly like canned answers.
"""

from __future__ import annotations

import calendar
from typing import Any

import numpy as np

from .question_tree import QUESTION_TREE

_GLOBAL_START_YEAR = 1979


# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------


def _tok(celsius: float, *, delta: bool = False, nd: int = 1) -> str:
    """Format a temperature as a [[C|F]] token. Delta values use scale-only conversion."""
    c = round(celsius, nd)
    f = round(c * 9 / 5 if delta else c * 9 / 5 + 32, nd)
    return f"[[{c}°C|{f}°F]]"


def _month_name(month: int) -> str:
    return calendar.month_name[month]


def _axis_month_name(axis_value: str) -> str:
    """'2003-08' → 'August 2003'."""
    year, month = str(axis_value).split("-")
    return f"{_month_name(int(month))} {year}"


# ---------------------------------------------------------------------------
# Data helpers
# ---------------------------------------------------------------------------


def _series(
    tile_store: Any, metric: str, lat: float, lon: float
) -> tuple[list, np.ndarray] | None:
    """Return (axis, values) for the snapped cell, or None if unavailable."""
    try:
        vec = tile_store.try_get_metric_vector(metric, lat, lon)
    except FileNotFoundError:
        return None
    if vec is None:
        return None
    axis = tile_store.axis(metric)
    values = np.asarray(vec, dtype=np.float64).reshape(-1)
    if axis is None or len(axis) != values.size:
        return None
    if np.count_nonzero(np.isfinite(values)) < 2:
        return None
    return list(axis), values


def _trend_per_decade(years: np.ndarray, values: np.ndarray) -> float | None:
    finite = np.isfinite(values)
    if np.count_nonzero(finite) < 2:
        return None
    return float(np.polyfit(years[finite], values[finite], 1)[0]) * 10


def _yearly(axis: list, values: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    years = np.asarray([int(str(a)[:4]) for a in axis], dtype=np.float64)
    return years, values


def _window_mean(values: np.ndarray, sl: slice) -> float | None:
    window = values[sl]
    finite = window[np.isfinite(window)]
    return float(np.mean(finite)) if finite.size else None


def _global_trend_per_decade(tile_store: Any, metric: str) -> float | None:
    agg = tile_store.aggregates.get((metric, "mean"))
    if not agg:
        return None
    globe = agg.get("regions", {}).get("globe")
    if not globe:
        return None
    values = np.asarray(
        [v if v is not None else np.nan for v in globe["values"]], dtype=np.float64
    )
    years = np.asarray(
        [int(str(a)[:4]) for a in agg["time_axis"]], dtype=np.float64
    )
    return _trend_per_decade(years, values)


def _monthly_typical_extreme(
    axis: list, values: np.ndarray, *, extreme: str, recent_years: int = 10
) -> tuple[float, int] | None:
    """
    Typical peak (or low) month over the last `recent_years` years of a
    monthly series: mean per calendar month, then max (or min) across months.
    Returns (value, month_number).
    """
    months = np.asarray([int(str(a).split("-")[1]) for a in axis])
    years = np.asarray([int(str(a)[:4]) for a in axis])
    cutoff = years.max() - recent_years + 1
    recent = years >= cutoff
    by_month: dict[int, float] = {}
    for m in range(1, 13):
        sel = values[recent & (months == m)]
        sel = sel[np.isfinite(sel)]
        if sel.size:
            by_month[m] = float(np.mean(sel))
    if not by_month:
        return None
    pick = max if extreme == "max" else min
    month = pick(by_month, key=by_month.get)
    return by_month[month], month


def _seasonal_yearly_means(
    axis: list, values: np.ndarray, months: list[int]
) -> tuple[np.ndarray, np.ndarray]:
    """Per-year mean over the given calendar months of a monthly series."""
    month_arr = np.asarray([int(str(a).split("-")[1]) for a in axis])
    year_arr = np.asarray([int(str(a)[:4]) for a in axis])
    sel = np.isin(month_arr, months)
    out_years, out_vals = [], []
    for y in np.unique(year_arr[sel]):
        vals = values[sel & (year_arr == y)]
        vals = vals[np.isfinite(vals)]
        if vals.size:
            out_years.append(float(y))
            out_vals.append(float(np.mean(vals)))
    return np.asarray(out_years), np.asarray(out_vals)


def _compare_to_global(local: float, global_: float | None) -> str:
    if global_ is None or global_ == 0:
        return ""
    ratio = local / global_
    if ratio >= 1.15:
        return f" — about {ratio:.1f}× the global average of {_tok(global_, delta=True, nd=2)} per decade"
    if ratio <= 0.85:
        return f" — slower than the global average of {_tok(global_, delta=True, nd=2)} per decade"
    return f" — close to the global average of {_tok(global_, delta=True, nd=2)} per decade"


# ---------------------------------------------------------------------------
# Per-question generators
# ---------------------------------------------------------------------------
# Each returns (answer_text, chart_spec) or None when the location has no
# usable data for the question. `label` is the display name from the map pin.


def _gen_local_temp_trend(tile_store, lat, lon, label):
    s = _series(tile_store, "t2m_yearly_mean_c", lat, lon)
    if s is None:
        return None
    axis, values = s
    years, values = _yearly(axis, values)
    trend = _trend_per_decade(years, values)
    first = _window_mean(values, slice(0, 5))
    last = _window_mean(values, slice(-5, None))
    if trend is None or first is None or last is None:
        return None
    global_trend = _global_trend_per_decade(tile_store, "t2m_yearly_mean_c")
    answer = (
        f"**{label}** has warmed at **{_tok(trend, delta=True, nd=2)} per decade** "
        f"since {int(years[0])}{_compare_to_global(trend, global_trend)}. "
        f"Its mean annual temperature rose from {_tok(first)} (average of the first five years) "
        f"to {_tok(last)} over the most recent five years."
    )
    return answer, {"metric_id": "t2m_yearly_mean_c", "show_trend": True}


def _gen_local_summer_heat(tile_store, lat, lon, label):
    s = _series(tile_store, "t2m_monthly_max_c", lat, lon)
    if s is None:
        return None
    axis, values = s
    typical = _monthly_typical_extreme(axis, values, extreme="max")
    if typical is None:
        return None
    typical_value, typical_month = typical
    idx = int(np.nanargmax(values))
    answer = (
        f"The hottest days in **{label}** typically reach about **{_tok(typical_value)}** "
        f"in {_month_name(typical_month)} (average over the last decade). "
        f"The highest temperature in our data is **{_tok(values[idx])}**, "
        f"recorded in {_axis_month_name(axis[idx])}. "
        f"The chart shows how the year's hottest days have trended over time."
    )
    return answer, {
        "metric_id": "t2m_monthly_max_c",
        "aggregate_by_year": True,
        "show_trend": True,
    }


